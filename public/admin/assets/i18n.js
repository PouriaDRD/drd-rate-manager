export const I18N_LANGUAGES = Object.freeze(["fa", "en"]);

export function normalizeLanguage(value) {
  return value === "en" ? "en" : "fa";
}

export function t(language, key) {
  const lang = normalizeLanguage(language);
  return COPY[lang][key] ?? COPY.fa[key] ?? key;
}

export function applyLanguage(language) {
  const lang = normalizeLanguage(language);
  document.documentElement.lang = lang;
  document.documentElement.dir = lang === "fa" ? "rtl" : "ltr";
  document.querySelectorAll("[data-i18n]").forEach((node) => {
    node.textContent = t(lang, node.dataset.i18n);
  });
  document.querySelectorAll("[data-i18n-placeholder]").forEach((node) => {
    node.placeholder = t(lang, node.dataset.i18nPlaceholder);
  });
  document.querySelectorAll("[data-i18n-aria]").forEach((node) => {
    node.setAttribute("aria-label", t(lang, node.dataset.i18nAria));
  });
}
